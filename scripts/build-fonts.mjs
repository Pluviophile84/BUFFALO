#!/usr/bin/env node
// Subset the self-hosted @fontsource faces to the glyphs this site sets, and
// compute metric-matched fallback faces (size-adjust / ascent-override) so the
// swap from fallback to webfont does not shift layout.
//
// Ƀ (U+0243) and ⟩ (U+27E9) are NOT in any of these fonts (verified here and in
// tests). They are rendered as inline SVG glyphs: Ƀ is the master's own path,
// ⟩ is drawn to JetBrains Mono's metrics (see src/components/Glyph.astro).
import fs from 'node:fs';
import path from 'node:path';
import subsetFont from 'subset-font';
import * as fontkit from 'fontkit';
import { entireMetricsCollection as M } from '@capsizecss/metrics/entireMetricsCollection';
import { ROOT } from './lib/master.mjs';

const NM = path.join(ROOT, 'node_modules');
const OUT = path.join(ROOT, 'src/assets/fonts');
fs.mkdirSync(OUT, { recursive: true });

// Basic Latin + the punctuation the copy uses. Kept deliberately small.
const range = (a, b) => Array.from({ length: b - a + 1 }, (_, i) => String.fromCodePoint(a + i)).join('');
const CHARSET =
  range(0x20, 0x7e) +
  ' ©°·×' + // nbsp © ° · ×
  '–—‘’“”…′″  '; // – — ‘ ’ “ ” … ′ ″ thin/hair space

const FACES = [
  { id: 'caslon-display', family: 'Libre Caslon Display', weight: '400', style: 'normal', src: '@fontsource/libre-caslon-display/files/libre-caslon-display-latin-400-normal.woff2', fallback: 'timesNewRoman', fallbackLocal: ['Times New Roman', 'Times', 'Liberation Serif', 'Tinos'] },
  { id: 'caslon-text', family: 'Libre Caslon Text', weight: '400', style: 'normal', src: '@fontsource/libre-caslon-text/files/libre-caslon-text-latin-400-normal.woff2', fallback: 'timesNewRoman', fallbackLocal: ['Times New Roman', 'Times', 'Liberation Serif', 'Tinos'] },
  { id: 'caslon-text-italic', family: 'Libre Caslon Text', weight: '400', style: 'italic', src: '@fontsource/libre-caslon-text/files/libre-caslon-text-latin-400-italic.woff2', fallback: 'timesNewRoman', fallbackVariant: 'italic', fallbackLocal: ['Times New Roman Italic', 'Times-Italic', 'Liberation Serif Italic', 'Tinos Italic'] },
  { id: 'caslon-text-bold', family: 'Libre Caslon Text', weight: '700', style: 'normal', src: '@fontsource/libre-caslon-text/files/libre-caslon-text-latin-700-normal.woff2', fallback: 'timesNewRoman', fallbackVariant: '700', fallbackLocal: ['Times New Roman Bold', 'Times-Bold', 'Liberation Serif Bold', 'Tinos Bold'] },
  // The site sets mono at one weight only: pin the variable font to a static 400 instance.
  { id: 'jetbrains-mono', family: 'JetBrains Mono', weight: '400', style: 'normal', src: '@fontsource-variable/jetbrains-mono/files/jetbrains-mono-latin-wght-normal.woff2', axes: { wght: 400 }, fallback: 'courierNew', fallbackLocal: ['Courier New', 'Liberation Mono', 'Cousine'] },
];

// Average character width weighted by English letter frequency (capsize method).
const FREQ = { ' ': 0.1872, e: 0.1006, t: 0.0712, a: 0.0646, o: 0.0587, n: 0.0563, i: 0.0563, s: 0.0525, h: 0.0476, r: 0.0466, d: 0.0331, l: 0.0322, u: 0.0218, c: 0.0207, m: 0.0193, w: 0.0174, f: 0.0167, g: 0.0154, y: 0.0145, p: 0.0130, b: 0.0115, v: 0.0080, k: 0.0057, x: 0.0013, j: 0.0010, q: 0.0008, z: 0.0006 };
const avgWidth = (font) => {
  let w = 0;
  let total = 0;
  for (const [ch, f] of Object.entries(FREQ)) {
    w += font.glyphForCodePoint(ch.codePointAt(0)).advanceWidth * f;
    total += f;
  }
  return w / total;
};

const pct = (n) => `${(n * 100).toFixed(4)}%`;
const report = {};
let css = `/* Generated by scripts/build-fonts.mjs — do not edit by hand. */\n`;

for (const face of FACES) {
  const srcBuf = fs.readFileSync(path.join(NM, face.src));
  const sub = await subsetFont(srcBuf, CHARSET, {
    targetFormat: 'woff2',
    ...(face.axes ? { variationAxes: face.axes } : {}),
  });
  const file = `${face.id}.woff2`;
  fs.writeFileSync(path.join(OUT, file), sub);

  const font = fontkit.create(srcBuf);
  for (const cp of [0x0243, 0x27e9]) {
    if (font.hasGlyphForCodePoint(cp)) console.warn(`  note: ${face.id} now contains U+${cp.toString(16)} — SVG glyph fallback could be retired`);
  }
  const fb = face.fallbackVariant ? M[face.fallback].variants[face.fallbackVariant] : M[face.fallback];
  const sizeAdjust = avgWidth(font) / font.unitsPerEm / (fb.xWidthAvg / fb.unitsPerEm);
  const ascent = font.ascent / font.unitsPerEm / sizeAdjust;
  const descent = Math.abs(font.descent) / font.unitsPerEm / sizeAdjust;
  const lineGap = (font.lineGap || 0) / font.unitsPerEm / sizeAdjust;

  const fam = face.family;
  css += `
@font-face {
  font-family: '${fam}';
  font-style: ${face.style};
  font-weight: ${face.weight};
  font-display: swap;
  src: url('../assets/fonts/${file}') format('woff2');
}
@font-face {
  font-family: '${fam} Fallback';
  font-style: ${face.style};
  font-weight: ${face.weight.split(' ')[0]};
  src: ${face.fallbackLocal.map((n) => `local('${n}')`).join(', ')};
  size-adjust: ${pct(sizeAdjust)};
  ascent-override: ${pct(ascent)};
  descent-override: ${pct(descent)};
  line-gap-override: ${pct(lineGap)};
}
`;
  report[face.id] = {
    bytes: sub.length,
    sourceBytes: srcBuf.length,
    unitsPerEm: font.unitsPerEm,
    ascent: font.ascent,
    descent: font.descent,
    capHeight: font.capHeight,
    xHeight: font.xHeight,
  };
}

// Metrics the SVG ⟩ glyph is drawn to (JetBrains Mono, wght 400).
const mono = fontkit.create(fs.readFileSync(path.join(NM, FACES.at(-1).src)));
const bar = mono.glyphForCodePoint(0x7c);
report.monoGlyph = {
  unitsPerEm: mono.unitsPerEm,
  advance: bar.advanceWidth,
  barBBox: bar.bbox,
  stem: bar.bbox.maxX - bar.bbox.minX,
};

fs.mkdirSync(path.join(ROOT, 'src/styles'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'src/styles/fonts.css'), css);
fs.mkdirSync(path.join(ROOT, 'src/data'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'src/data/fonts.json'), JSON.stringify({ charset: CHARSET, faces: report }, null, 2) + '\n');

let total = 0;
for (const [id, r] of Object.entries(report)) {
  if (!r.bytes) continue;
  total += r.bytes;
  console.log(`  ${id.padEnd(20)} ${String(r.bytes).padStart(6)} B (from ${r.sourceBytes})`);
}
console.log(`  total ${total} B`);
console.log('build-fonts: done');
